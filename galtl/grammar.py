COMPILED: list[tuple[Grammar, re.Pattern]] = [
    (Grammar(p, lv, mean, exp, rx, pr), re.compile(rx))
    for p, lv, mean, exp, rx, pr in _RAW
]


def match(text: str, limit: int = 6) -> list[dict]:
    """返回命中的语法条目（按优先级与位置排序）。"""
    if not text:
        return []
    hits = []
    for g, rx in COMPILED:
        m = rx.search(text)
        if not m:
            continue
        frag = m.group(0)
        hits.append(
            {
                "pattern": g.pattern,
                "level": g.level,
                "meaning": g.meaning,
                "explain": g.explain,
                "form": frag,
                "pos": m.start(),
                "prio": g.prio,
                "source": "local",
            }
        )
    hits.sort(key=lambda h: (-h["prio"], h["pos"]))
    out = []
    seen = set()
    for h in hits:
        if h["pattern"] in seen:
            continue
        seen.add(h["pattern"])
        out.append(h)
        if len(out) >= limit:
            break
    out.sort(key=lambda h: h["pos"])
    return out


def as_hint(text: str, limit: int = 6) -> str:
    """给大模型的提示串。"""
    hits = match(text, limit=limit)
    if not hits:
        return "（本地词组库未命中固定句型，请按句子实际结构分析）"
    return "\n".join(f"- {h['pattern']}（{h['level']}）{h['meaning']}｜片段：{h['form']}" for h in hits)



# 长的先匹配（「お母さん」不该被「母」抢先，虽然这里没有「母」）
_SORTED = tuple(sorted(WORDS, key=lambda w: -len(w[0])))


def quick(jp_text: str, limit: int = 4) -> list[dict]:
    """从一句话里挑出词表命中的词，按出现顺序返回（最多 limit 个）。"""
    if not jp_text:
        return []
    hits: list[tuple[int, dict]] = []
    taken = [False] * len(jp_text)          # 已被更长的词占用的字符位置
    for word, reading, pos, meaning in _SORTED:
        start = 0
        while True:
            i = jp_text.find(word, start)
            if i < 0:
                break
            start = i + 1
            if any(taken[i:i + len(word)]):
                continue
            for k in range(i, i + len(word)):
                taken[k] = True
            hits.append((i, {"word": word, "reading": reading, "pos": pos,
                             "meaning": meaning, "quick": True}))
    hits.sort(key=lambda x: x[0])
    out: list[dict] = []
    seen: set[str] = set()
    for _i, item in hits:
        if item["word"] in seen:
            continue
        seen.add(item["word"])
        out.append(item)
        if len(out) >= limit:
            break
    return out
